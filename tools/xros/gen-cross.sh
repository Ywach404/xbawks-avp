#!/usr/bin/env bash
# Emit a meson cross file for arm64-apple-xros.
#
#   ./gen-cross.sh                -> xros-arm64.cross            (device)
#   ./gen-cross.sh simulator      -> xros-arm64-simulator.cross
#
# Everything is written absolute, so re-run this after moving the sysroot.
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
VARIANT="${1:-device}"
MINVER="${XROS_DEPLOYMENT_TARGET:-26.0}"

case "$VARIANT" in
device)
	SDK=xros
	TRIPLE="arm64-apple-xros${MINVER}"
	SYSROOT="$HERE/sysroot-visionos-arm64/sysroot-visionos-arm64"
	SUBSYSTEM=visionos
	SUFFIX=""
	OUT="$HERE/xros-arm64.cross"
	;;
simulator)
	SDK=xrsimulator
	TRIPLE="arm64-apple-xros${MINVER}-simulator"
	SYSROOT="$HERE/sysroot-visionos_simulator-arm64/sysroot-visionos_simulator-arm64"
	SUBSYSTEM=visionos-simulator
	SUFFIX="-simulator"
	OUT="$HERE/xros-arm64-simulator.cross"
	;;
*)
	echo "usage: gen-cross.sh [device|simulator]" >&2
	exit 1
	;;
esac

[[ -d "$SYSROOT/lib/pkgconfig" ]] || { echo "no sysroot at $SYSROOT" >&2; exit 1; }
SDKROOT="$(xcrun --sdk $SDK --show-sdk-path)"
GLSLANG="$HERE/glslang-xros${SUFFIX:-}"

# Shared flag blocks. The sysroot's include and Frameworks are added for every
# language; the link side also plants the one rpath the app bundle will use.
CARGS="'-arch', 'arm64', '-isysroot', '$SDKROOT', '-I$SYSROOT/include', '-F$SYSROOT/Frameworks'"
LARGS="'-arch', 'arm64', '-isysroot', '$SDKROOT', '-L$SYSROOT/lib', '-F$SYSROOT/Frameworks', '-Wl,-rpath,@executable_path/Frameworks'"

cat > "$OUT" <<EOF
# meson cross file: $TRIPLE
# Generated by gen-cross.sh. Re-run it rather than editing by hand.
#
# system = 'darwin', not 'ios'.
#   UTM writes system = 'ios' for its own libraries, and libslirp needs that
#   (UTM's libslirp patch widens a darwin branch to 'ios' to pick up -lresolv).
#   QEMU is the opposite case: it has many host_os == 'darwin' branches for
#   Mach, CoreFoundation and the Darwin signal and coroutine paths, and
#   system = 'ios' silently loses all of them. UTM itself does not build QEMU
#   through its own cross file: it runs configure with --cross-prefix="",
#   and the config-meson.cross that configure emits says darwin.
#   subsystem = '$SUBSYSTEM' is what carries the platform distinction.
#
# has_function_pipe2 / has_function_dup3 = false.
#   pipe2() and dup3() are new in the 27.0 SDKs. meson's has_function()
#   declares its own prototype, so it never sees the availability attribute
#   and reports them present whatever the deployment target. The real call
#   sites include the system header, which leaves a weak import that is NULL
#   at runtime on an older OS. Taken from UTM verbatim.

[binaries]
c         = ['clang', '-target', '$TRIPLE']
cpp       = ['clang++', '-target', '$TRIPLE']
objc      = ['clang', '-target', '$TRIPLE']
objcpp    = ['clang++', '-target', '$TRIPLE']
ar        = '$(xcrun --sdk $SDK --find ar)'
nm        = '$(xcrun --sdk $SDK --find nm)'
ranlib    = '$(xcrun --sdk $SDK --find ranlib)'
strip     = ['$(xcrun --sdk $SDK --find strip)', '-x']
pkg-config = 'pkg-config'
cmake     = '$(command -v cmake)'

[properties]
needs_exe_wrapper = true
has_function_pipe2 = false
has_function_dup3 = false
# Only these. Without pkg_config_libdir the host's /opt/homebrew/lib/pkgconfig
# leaks in and a macOS .dylib gets picked up for a visionOS link.
pkg_config_libdir = ['$SYSROOT/lib/pkgconfig', '$SYSROOT/share/pkgconfig', '$GLSLANG/lib/pkgconfig', '$HERE/sdl3-xros/lib/pkgconfig', '$HERE/samplerate-xros/lib/pkgconfig']
# CMake subprojects (volk and spirv-reflect in the consuming tree) need the
# matching toolchain or they quietly build for the host.
cmake_toolchain_file = '$HERE/xros.cmake'
cmake_defaults = false

[built-in options]
c_args = [$CARGS]
cpp_args = [$CARGS]
objc_args = [$CARGS]
objcpp_args = [$CARGS]
c_link_args = [$LARGS]
cpp_link_args = [$LARGS]
objc_link_args = [$LARGS]
objcpp_link_args = [$LARGS]

[host_machine]
system     = 'darwin'
kernel     = 'xnu'
subsystem  = '$SUBSYSTEM'
cpu_family = 'aarch64'
cpu        = 'arm64'
endian     = 'little'
EOF

echo "wrote $OUT"

# A properties-only companion, for layering on top of a cross file that another
# build system generated (QEMU's configure writes its own config-meson.cross
# from the environment). Meson merges cross files left to right, but a later
# [built-in options] section REPLACES the earlier one rather than appending to
# it, so handing the full file to configure silently drops its -D defines and
# --extra-cflags. This file carries only the parts configure does not produce.
PROPS="${OUT%.cross}-props.cross"
cat > "$PROPS" <<EOF2
# Layering companion to $(basename "$OUT"). Properties and binaries only.
# Deliberately no [built-in options]: a later cross file replaces that section
# wholesale, which would discard the flags configure built from the
# environment. Pass this one with configure's --extra-cross-file.

[binaries]
# configure derives objc from \$OBJCC without a target triple, which leaves
# CMake subprojects compiling .m files for macOS and failing at the link with
# "building for visionOS, but linking in object file built for macOS".
objc   = ['clang', '-target', '$TRIPLE']
objcpp = ['clang++', '-target', '$TRIPLE']

[properties]
needs_exe_wrapper = true
has_function_pipe2 = false
has_function_dup3 = false
pkg_config_libdir = ['$SYSROOT/lib/pkgconfig', '$SYSROOT/share/pkgconfig', '$GLSLANG/lib/pkgconfig', '$HERE/sdl3-xros/lib/pkgconfig', '$HERE/samplerate-xros/lib/pkgconfig']
cmake_toolchain_file = '$HERE/xros$( [ "$VARIANT" = simulator ] && echo -simulator ).cmake'
cmake_defaults = false

[host_machine]
system     = 'darwin'
kernel     = 'xnu'
subsystem  = '$SUBSYSTEM'
cpu_family = 'aarch64'
cpu        = 'aarch64'
endian     = 'little'
EOF2
echo "wrote $PROPS"
